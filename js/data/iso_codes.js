/**
 * Verilen ülke isminin ISO kodunu bulur.
 * @param {string} name - Ülke ismi (örn: "Turkey", "turkey", "TÜRKİYE")
 * @returns {string} - "tr", "us", "de" gibi 2 harfli kod. Bulamazsa "un".
 */
export function getCountryCode(name) {
    if (!name) return "un";

    // Temizle ve küçük harfe çevir
    const clean = name.trim().toLowerCase();

    return CountryCodeMap[clean] || "un";
}
