// Bir eyaletin kıyı eyaleti olup olmadığını kontrol et
export function isCoastalRegion(regionId) {
    return coastalRegions.includes(regionId);
}

// Bir ülkenin tüm kıyı şehirlerini getir
export function getCountryCoastalCities(countryName) {
    try {
        // Şehir verilerini al
        const rawCityLookup = localStorage.getItem('nomos_city_lookup');
        if (!rawCityLookup) {
            console.warn("nomos_city_lookup bulunamadı. Önce haritayı açın.");
            return [];
        }

        const cityLookup = JSON.parse(rawCityLookup);

        // Bina verilerini al (mevcut binalar için)
        const rawMapData = localStorage.getItem('nomos_map_data') || '{}';
        const mapData = JSON.parse(rawMapData);

        // ISO kodu ile normalize et
        const targetCode = normalizeCountryName(countryName);

        const coastalCities = [];

        Object.keys(cityLookup).forEach(regionId => {
            const city = cityLookup[regionId];
            const savedData = mapData[regionId] || {};
            const cityCode = normalizeCountryName(city.country);

            // ISO kodu ile ülke eşleşmesi ve kıyı kontrolü
            if (cityCode === targetCode && isCoastalRegion(regionId)) {
                coastalCities.push({
                    id: regionId,
                    name: city.name || regionId,
                    hasHarbor: (savedData.buildings || []).includes('port')
                });
            }
        });

        return coastalCities;
    } catch (e) {
        console.error("Kıyı şehirleri alınamadı:", e);
        return [];
    }
}

