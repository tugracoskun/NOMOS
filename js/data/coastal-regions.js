function normalizeCountryName(name) {
    if (!name) return "unknown";
    const clean = name.trim().toLowerCase();
    return countryNormMap[clean] || clean;
}

// Bir ülkenin limanı var mı kontrol et
export function countryHasHarbor(countryName) {
    const coastalCities = getCountryCoastalCities(countryName);
    return coastalCities.some(city => city.hasHarbor);
}

// Liman inşa et (State'e kaydet)
export function buildHarborInCity(regionId) {
    try {
        const rawMap = localStorage.getItem('nomos_map_data');
        if (!rawMap) return { success: false, error: 'Harita verisi bulunamadı' };

        const mapData = JSON.parse(rawMap);

        if (!mapData[regionId]) {
            return { success: false, error: 'Şehir bulunamadı' };
        }

        if (!isCoastalRegion(regionId)) {
            return { success: false, error: 'Bu şehir kıyıda değil!' };
        }

        // Binalar dizisine ekle
        if (!mapData[regionId].buildings) {
            mapData[regionId].buildings = [];
        }

        if (mapData[regionId].buildings.includes('port')) {
            return { success: false, error: 'Bu şehirde zaten liman var!' };
        }

        mapData[regionId].buildings.push('port');
        localStorage.setItem('nomos_map_data', JSON.stringify(mapData));

        return { success: true, cityName: mapData[regionId].name };
    } catch (e) {
        console.error("Liman inşa hatası:", e);
        return { success: false, error: 'Bir hata oluştu' };
    }
}

